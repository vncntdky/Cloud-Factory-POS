const { chromium } = require("playwright");
const b64url = (s) => Buffer.from(s).toString("base64url");
const exp = Math.floor(Date.now() / 1000) + 86400;
const jwt = [b64url('{"alg":"HS256"}'), b64url(JSON.stringify({ sub: "aaaaaaaa-1111-4111-8111-000000000001", exp })), b64url("signature")].join(".");
const session = { access_token: jwt, refresh_token: "r", token_type: "bearer", expires_in: 86400, expires_at: exp, user: { id: "aaaaaaaa-1111-4111-8111-000000000001" } };
(async () => {
  const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
  const r = [];
  const check = (n, ok, x = "") => r.push(`${ok ? "ok  " : "FAIL"} ${n}${x ? ` (${x})` : ""}`);
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  await ctx.addCookies([{ name: "sb-127-auth-token", value: "base64-" + b64url(JSON.stringify(session)), domain: "127.0.0.1", path: "/" }]);
  const page = await ctx.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.goto("http://127.0.0.1:3100/restock/receive");
  const chips = await page.locator('[aria-label="Category"] .filter-chip').allInnerTexts();
  check("category chips: All + each category", chips.join("|") === "All|TRANSPARENT V2 PODS|Black TEO", chips.join("|"));
  const visible = async () => page.locator("li.receive-row:visible").count();
  check("All shows every product", (await visible()) === 10);
  await page.getByRole("button", { name: "Black TEO" }).click();
  check("a category shows only its products", (await visible()) === 4);
  await page.getByLabel("Pieces of XBLACK MAX Pods · Ice Monkey").fill("").catch(() => {});
  const first = page.locator("li.receive-row:visible").first();
  await first.locator('input[name^="qty_"]').fill("12");
  check("chip shows pieces entered in that category", /Black TEO\s*12 pcs/.test(await page.getByRole("button", { name: /Black TEO/ }).innerText()));
  await page.getByRole("button", { name: /TRANSPARENT V2 PODS/ }).click();
  check("switching category keeps what was entered", /12 pcs/.test(await page.locator(".actionbar__total").innerText()) && (await visible()) === 6);
  await page.locator("li.receive-row:visible").first().locator('input[name^="qty_"]').fill("5");
  check("total counts every category", /17 pcs/.test(await page.locator(".actionbar__total").innerText()));
  await page.screenshot({ path: __dirname + "/shots/receive-cat.png", fullPage: false });
  await page.getByRole("button", { name: "Receive batch" }).last().click();
  await page.waitForURL(/\/restock\/batches\/[0-9a-f-]{36}\?received=1/, { waitUntil: "commit" });
  const log = (await (await fetch("http://127.0.0.1:54321/__log")).json()).log;
  const items = log.filter((l) => l.rpc === "receive_batch").at(-1).body.p.items;
  check("batch includes products from both categories", items.length === 2 && items.map((i) => i.qty).sort().join(",") === "12,5", JSON.stringify(items.map((i) => i.qty)));
  check("no page errors", errors.length === 0, errors.join("; "));
  console.log(r.join("\n"));
  await browser.close();
})();
