const { chromium } = require("playwright");
const b64url = (s) => Buffer.from(s).toString("base64url");
const exp = Math.floor(Date.now() / 1000) + 86400;
const jwt = [b64url('{"alg":"HS256"}'), b64url(JSON.stringify({ sub: "aaaaaaaa-1111-4111-8111-000000000001", exp })), b64url("signature")].join(".");
const session = { access_token: jwt, refresh_token: "r", token_type: "bearer", expires_in: 86400, expires_at: exp, user: { id: "aaaaaaaa-1111-4111-8111-000000000001" } };
const B = "http://127.0.0.1:3100";
(async () => {
  const browser = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" });
  const r = [];
  const check = (n, ok, x = "") => r.push(`${ok ? "ok  " : "FAIL"} ${n}${x ? ` (${x})` : ""}`);
  const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  await ctx.addCookies([{ name: "sb-127-auth-token", value: "base64-" + b64url(JSON.stringify(session)), domain: "127.0.0.1", path: "/" }]);
  const page = await ctx.newPage();
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.goto(`${B}/restock?view=batches`);
  await page.getByRole("button", { name: "Add expense" }).click();
  const opts = await page.locator("#exp-batch option").allInnerTexts();
  check("with no batches, Charge to offers only General", opts.length === 1);
  check("and says how to get a batch", (await page.getByRole("link", { name: "Turn your current stock into a batch" }).count()) === 1);
  await page.getByRole("link", { name: "Turn your current stock into a batch" }).click();
  await page.waitForURL(/\/restock\/batches\/before/, { waitUntil: "commit" });
  await page.screenshot({ path: __dirname + "/shots/make-batch.png", fullPage: true });
  await page.fill("#mb-supplier", "Cloud Supply");
  await page.getByRole("button", { name: "Turn into a batch" }).click();
  await page.waitForURL(/\/restock\/batches\/[0-9a-f-]{36}\?made=1/, { waitUntil: "commit" });
  await page.getByText("Batch 1 made from your earlier stock.").waitFor();
  check("stock becomes Batch 1 with its own P&L", (await page.locator("#pnl").count()) === 1 && (await page.locator("#make-batch-t").count()) === 0);
  await page.goto(`${B}/restock?view=batches`);
  await page.getByRole("button", { name: "Add expense" }).click();
  const opts2 = await page.locator("#exp-batch option").allInnerTexts();
  check("Charge to now offers General and Batch 1", opts2.length === 2 && /General/.test(opts2[0]) && /Batch 1 · Cloud Supply/.test(opts2[1]), opts2.join(" | "));
  check("Stock before batches is gone from the list", (await page.getByText("Stock before batches").count()) === 0);
  check("no page errors", errors.length === 0, errors.join("; "));
  console.log(r.join("\n"));
  await browser.close();
})();
